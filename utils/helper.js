export function encrypt2(text) {
  const CryptoJS = require("crypto-js");
  let key = "shareadscanner";
  try {
    // Hash the key using CryptoJS
    const hashedKey = CryptoJS.SHA256(key);
    // Use the hashed key directly, as it is already in a compatible format
    const encrypted = CryptoJS.AES.encrypt(text, hashedKey, {
      mode: CryptoJS.mode.ECB,
      padding: CryptoJS.pad.Pkcs7,
    });
    return encrypted.toString();
  } catch (error) {
    console.error("Encryption error:", error);
    return null;
  }
}

