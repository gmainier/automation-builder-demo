export function decrypt(encryptedText) {
  const CryptoJS = require("crypto-js");
  let key = "milkshakeadscanner";

  // Check if encryptedText is null or undefined
  if (!encryptedText || encryptedText === null || encryptedText === undefined) {
    console.error("Decryption error: encryptedText is null or undefined");
    return "";
  }

  try {
    // Hash the key using CryptoJS
    const hashedKey = CryptoJS.SHA256(key);
    // Use the hashed key directly for decryption
    const decryptedData = CryptoJS.AES.decrypt(encryptedText, hashedKey, {
      mode: CryptoJS.mode.ECB,
      padding: CryptoJS.pad.Pkcs7,
    });
    return decryptedData.toString(CryptoJS.enc.Utf8);
  } catch (error) {
    console.error("Decryption error:", error);
    return "";
  }
}

export function encrypt(text) {
  const CryptoJS = require("crypto-js");
  let key = "milkshakeadscanner";
  try {
    // Hash the key using CryptoJS
    const hashedKey = CryptoJS.SHA256(key);
    // Use the hashed key directly, as it is already in a compatible format
    const encrypted = CryptoJS.AES.encrypt(text, hashedKey, {
      mode: CryptoJS.mode.ECB,
      padding: CryptoJS.pad.Pkcs7,
    });
    return encrypted.toString();
  } catch (error) {
    console.error("Encryption error:", error);
    return null;
  }
}

export function kFormatter(num, digits) {
  var si = [
    { value: 1, symbol: "" },
    { value: 1e3, symbol: "k" },
    { value: 1e6, symbol: "M" },
    { value: 1e9, symbol: "B" },
    { value: 1e12, symbol: "T" },
    { value: 1e15, symbol: "P" },
    { value: 1e18, symbol: "E" },
  ];
  var rx = /\.0+$|(\.[0-9]*[1-9])0+$/;
  var i;
  for (i = si.length - 1; i > 0; i--) {
    if (num >= si[i].value) {
      break;
    }
  }
  return (num / si[i].value).toFixed(digits).replace(rx, "$1") + si[i].symbol;
}

export function transformDate(dateStr) {
  // Split the string into day, month, and year
  const [month, day, year] = dateStr.split("/");

  // Create an array of month names for conversion
  const monthNames = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

  // Convert month number to month name using the monthNames array
  const monthName = monthNames[parseInt(month, 10) - 1];

  // Return the transformed string
  return `${monthName} ${day} ${year}`;
}

